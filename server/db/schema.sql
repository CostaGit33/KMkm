CREATE TABLE IF NOT EXISTS turmas (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  codigo_convite VARCHAR(40) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS usuarios (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  apelido VARCHAR(30) NOT NULL,
  token VARCHAR(128) NULL UNIQUE,
  turma_id INT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT usuarios_turma_fk FOREIGN KEY (turma_id) REFERENCES turmas(id)
);
CREATE TABLE IF NOT EXISTS contas (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  usuario_id INT NOT NULL UNIQUE,
  nome VARCHAR(80) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  senha_hash VARBINARY(128) NOT NULL,
  senha_salt VARBINARY(32) NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT contas_usuario_fk FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS sessoes (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  conta_id INT NOT NULL,
  token_hash BINARY(32) NOT NULL UNIQUE,
  expira_em DATETIME NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT sessoes_conta_fk FOREIGN KEY (conta_id) REFERENCES contas(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS rotas (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(160) NOT NULL UNIQUE,
  tipo VARCHAR(20) NOT NULL,
  cor VARCHAR(20) NOT NULL,
  km DECIMAL(8,2) NULL,
  cidade_id VARCHAR(64) NOT NULL DEFAULT 'eunapolis',
  status VARCHAR(24) NOT NULL DEFAULT 'publicado'
);
CREATE TABLE IF NOT EXISTS tags (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo VARCHAR(80) NOT NULL UNIQUE,
  rota_id INT NOT NULL,
  ordem INT NOT NULL,
  nome VARCHAR(160) NOT NULL,
  forma VARCHAR(1) NOT NULL DEFAULT 'c',
  parceiro BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(24) NOT NULL DEFAULT 'publicado',
  CONSTRAINT tags_rota_fk FOREIGN KEY (rota_id) REFERENCES rotas(id)
);
CREATE TABLE IF NOT EXISTS carimbos (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  usuario_id INT NOT NULL,
  tag_id INT NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  seed INT NOT NULL,
  especial VARCHAR(20) NULL,
  CONSTRAINT carimbos_usuario_fk FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
  CONSTRAINT carimbos_tag_fk FOREIGN KEY (tag_id) REFERENCES tags(id)
);
