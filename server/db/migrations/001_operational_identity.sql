CREATE TABLE IF NOT EXISTS contas (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  usuario_id INT NOT NULL UNIQUE,
  nome VARCHAR(80) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  senha_hash VARBINARY(128) NOT NULL,
  senha_salt VARBINARY(32) NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT contas_usuario_fk FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS sessoes (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  conta_id INT NOT NULL,
  token_hash BINARY(32) NOT NULL UNIQUE,
  expira_em DATETIME NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT sessoes_conta_fk FOREIGN KEY (conta_id) REFERENCES contas(id) ON DELETE CASCADE
);
